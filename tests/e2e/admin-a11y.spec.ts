test.describe("ledger checks", () => {
  test("the sticky editor bar sets main's scroll padding (WCAG 2.4.11)", async ({
    page,
  }) => {
    await signIn(page, readFixtures().editor)
    await page.goto("/admin/pages/home")
    await expect(
      page.getByRole("status", { name: /^Save status/ })
    ).toBeVisible()
    const bar = page.locator('[data-slot="editor-bar"]')
    // offsetHeight, as the layout measures it (whole pixels).
    const barHeight = await bar.evaluate(
      (el) => (el as HTMLElement).offsetHeight
    )
    const main = page.getByRole("main")
    await expect
      .poll(() =>
        main.evaluate(
          (el) => parseFloat(getComputedStyle(el).scrollPaddingTop) || 0
        )
      )
      .toBe(barHeight + 16)
    // Focus a visible field below the fold: it lands under the bar, not
    // behind it (the focusin handler scrolls the panel by the overlap).
    const last = page
      .locator('[data-slot="editor-form"]')
      .getByRole("textbox")
      .last()
    await last.focus()
    await expect(last).toBeFocused()
    await expect
      .poll(async () => {
        const [fieldTop, barBottom] = await Promise.all([
          last.evaluate((el) => el.getBoundingClientRect().top),
          bar.evaluate((el) => el.getBoundingClientRect().bottom),
        ])
        return fieldTop - barBottom
      })
      .toBeGreaterThanOrEqual(0)
  })

  test("a record sheet traps focus and returns it to its opener", async ({
    page,
  }) => {
    await signIn(page, readFixtures().editor)
    await page.goto("/admin/collections/team")
    const opener = page
      .getByRole("button", { name: "Edit Michael McDonald" })
      .first()
    await opener.click()
    const sheet = page.getByRole("dialog", { name: "Team member" })
    await expect(sheet).toBeVisible()
    // Focus starts inside and stays inside through a full Tab cycle.
    for (let i = 0; i < 40; i++) {
      await page.keyboard.press("Tab")
      await expect(sheet.locator(":focus")).toHaveCount(1)
    }
    await page.keyboard.press("Shift+Tab")
    await expect(sheet.locator(":focus")).toHaveCount(1)
    await page.keyboard.press("Escape")
    await expect(sheet).toHaveCount(0)
    await expect(opener).toBeFocused()
  })
})
